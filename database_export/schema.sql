-- Import into an EMPTY database. No existing tables or records are deleted.
SET NAMES utf8mb4;

CREATE TABLE Account (
 AccountID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 Email VARCHAR(254) NOT NULL UNIQUE,
 Password VARCHAR(255) NOT NULL,
 Created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 Updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 Active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE `User` (
 UserID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 Name VARCHAR(80) NOT NULL,
 AccountID INT UNSIGNED NOT NULL UNIQUE,
 Created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 Updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 Active TINYINT(1) NOT NULL DEFAULT 1,
 FOREIGN KEY (AccountID) REFERENCES Account(AccountID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE Product (
 ProductID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 Name VARCHAR(100) NOT NULL,
 Description VARCHAR(1000) NOT NULL,
 Brand VARCHAR(100) NOT NULL DEFAULT 'Independent',
 Suburb VARCHAR(80) NOT NULL,
 CoffeeStyle VARCHAR(80) NOT NULL,
 BeanOrigin VARCHAR(80) NOT NULL,
 Roast VARCHAR(40) NOT NULL,
 TastingNotes VARCHAR(150) NOT NULL,
 CoffeeDescription VARCHAR(1000) NOT NULL,
 PriceFrom DECIMAL(6,2) NOT NULL,
 PriceTo DECIMAL(6,2) NOT NULL,
 Created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 Updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 Active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE Image (
 ImageID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 Filename VARCHAR(255) NOT NULL,
 Caption VARCHAR(150) NOT NULL,
 Created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 Updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 Active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE Product_Image (
 ProductID INT UNSIGNED NOT NULL,
 ImageID INT UNSIGNED NOT NULL,
 PRIMARY KEY(ProductID,ImageID),
 FOREIGN KEY (ProductID) REFERENCES Product(ProductID) ON DELETE CASCADE,
 FOREIGN KEY (ImageID) REFERENCES Image(ImageID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE Review (
 ReviewID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 Title VARCHAR(80) NOT NULL,
 Body VARCHAR(2000) NOT NULL,
 ProductID INT UNSIGNED NOT NULL,
 UserID INT UNSIGNED NOT NULL,
 Rating TINYINT UNSIGNED NOT NULL CHECK (Rating BETWEEN 1 AND 5),
 AtmosphereRating TINYINT UNSIGNED NOT NULL CHECK (AtmosphereRating BETWEEN 1 AND 5),
 ServiceRating TINYINT UNSIGNED NOT NULL CHECK (ServiceRating BETWEEN 1 AND 5),
 Created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 Updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 Active TINYINT(1) NOT NULL DEFAULT 1,
 UNIQUE KEY one_review_per_user (ProductID,UserID),
 FOREIGN KEY (ProductID) REFERENCES Product(ProductID) ON DELETE CASCADE,
 FOREIGN KEY (UserID) REFERENCES `User`(UserID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE Favourite (
 UserID INT UNSIGNED NOT NULL,
 ProductID INT UNSIGNED NOT NULL,
 Created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(UserID,ProductID),
 FOREIGN KEY (UserID) REFERENCES `User`(UserID) ON DELETE CASCADE,
 FOREIGN KEY (ProductID) REFERENCES Product(ProductID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE LoginAttempt (
 AttemptID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 AttemptKey CHAR(64) NOT NULL,
 Created DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX attempt_window (AttemptKey,Created),
 INDEX created_cleanup (Created)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
